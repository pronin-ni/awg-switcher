func TestAutoReplenishmentGeneratorUnavailableAndRateLimited(t *testing.T) {
	for _, tc := range []struct {
		name       string
		err        error
		wantStatus string
		retry      time.Duration
	}{{"unavailable", errors.New("offline"), "unavailable", 0}, {"rate limited", &configGeneratorAPIError{StatusCode: 429, RetryAfter: 2 * time.Hour}, "unavailable", 2 * time.Hour}} {
		t.Run(tc.name, func(t *testing.T) {
			s := newAutoTestServer(t)
			autoReadyPrimary(s.controller)
			configureAutoRun(t, s, generatedConfigResponse{}, tc.err)
			if err := s.runAutoReplenishment(context.Background()); err == nil {
				t.Fatal("generator error was swallowed")
			}
			if s.autoState.LastRunStatus != tc.wantStatus || s.autoState.CooldownUntil.IsZero() {
				t.Fatalf("failure state=%+v", s.autoState)
			}
			if tc.retry > 0 && time.Until(s.autoState.CooldownUntil) < tc.retry-time.Second {
				t.Fatal("Retry-After was not retained")
			}
			if len(s.controller.profilesSnapshot()) != 1 {
				t.Fatal("candidate created on generator error")
			}
		})
	}

	t.Run("cleanup disabled", func(t *testing.T) {
		s, candidate, _ := newAutoCleanupTestServer(t, ProfileOriginAutoGenerated, false, 25*time.Hour)
		cfg := defaultCleanupTestConfig()
		cfg.AutoDeleteFailed = false
		removed, err := s.cleanupAutoFailedProfiles(context.Background(), cfg, 0, false)
		if err != nil || removed != 0 || s.controller.findProfile(candidate.ID) == nil {
			t.Fatalf("disabled cleanup removed=%d err=%v", removed, err)
		}
	})
	t.Run("active profile and last profile are protected", func(t *testing.T) {
		for _, active := range []bool{true, false} {
			s, candidate, _ := newAutoCleanupTestServer(t, ProfileOriginAutoGenerated, false, 25*time.Hour)
			if active {
				s.controller.active.Store(candidate)
			} else {
				s.controller.profiles = []*Profile{candidate}
				s.controller.active.Store(nil)
			}
			s.autoCleanupCheck = func(context.Context, *Profile) healthResult {
				return healthResult{Reason: "timeout", Revision: candidate.configRevision}
			}
			removed, err := s.cleanupAutoFailedProfiles(context.Background(), defaultCleanupTestConfig(), 0, false)
			if err != nil || removed != 0 || s.controller.findProfile(candidate.ID) == nil {
				t.Fatalf("active=%t cleanup removed=%d err=%v", active, removed, err)
			}
		}
	})
}

