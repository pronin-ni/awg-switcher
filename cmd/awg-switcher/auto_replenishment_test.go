func autoReadyPrimary(c *Controller) *Profile {
	p := &Profile{ID: "primary", Name: "primary", Priority: 0, State: "HEALTHY", Healthy: true, ConnectivityOK: true, RoutingEligible: true, enabled: true, LastCheck: time.Now(), config: []byte("existing-primary-config")}
	c.profiles = []*Profile{p}
	c.active.Store(p)
	return p
}

func validGeneratedPayload() string {
	config := strings.Replace(validWG, "Endpoint = vpn.example.test:51820", "Endpoint = generated.example.test:51820", 1)
	config = strings.Replace(config, ", ::/0", "", 1)
	return base64.StdEncoding.EncodeToString([]byte(config))
}

func generatorResult(configs ...string) generatedConfigResponse {
	r := generatedConfigResponse{Success: true, Count: len(configs)}
	for _, content := range configs {
		r.Configs = append(r.Configs, struct {
			Content string `json:"content"`
		}{Content: content})
	}
	return r
}

func configureAutoRun(t *testing.T, s *webServer, response generatedConfigResponse, requestErr error) {
	t.Helper()
	if err := s.saveGeneratorSettings(configGeneratorSettings{URL: "http://awg-config-gen:3000"}); err != nil {
		t.Fatal(err)
	}
	s.autoConfig = defaultAutoReplenishmentConfig()
	s.autoConfig.Enabled = true
	s.autoConfig.MinimumReady = 2
	s.autoConfig.TargetReady = 4
	s.autoConfig.AutoActivate = false
	s.controller.maxEngines = 20
	s.autoRunFunc = func(_ context.Context, _ configGeneratorSettings, mode string, count int) (generatedConfigResponse, error) {
		if mode != "awg2" {
			t.Errorf("generator mode=%q, want awg2", mode)
		}
		if count != 3 {
			t.Errorf("generator count=%d, want 3", count)
		}
		return response, requestErr
	}
}

